import type { LevelData } from '../../core/map-format';

/**
 * 地图文件模板说明
 * ----------------
 * - meta.id   : 全局唯一，存档用，不要和其他地图重复
 * - meta.name : 显示名
 * - meta.hint : 选关界面提示
 * - grid      : 字符串数组，每个字符是一格 16x16 像素
 *
 * 可用字符（图例）：
 *   '#'  实心方块（墙/地面）
 *   '='  单向平台（可从下往上跳穿，按住 下+跳 下落）
 *   '-'  装饰横木（无碰撞）
 *   '^'  尖刺（触碰死亡）
 *   '~'  岩浆（触碰立即死亡）
 *   'o'  金币
 *   'S'  出生点（每张图必须恰好一个）
 *   'E'  终点传送门（可多个，进入任意一个即通关）
 *   'C'  检查点旗帜
 *   'B'  弹跳板
 *   '>'  向右加速带    '<' 向左加速带
 *   'M'  水平移动平台   'm' 垂直移动平台
 *   '.' 或空格  空气
 *
 * 手感参考（调图用）：
 *   跳跃高度 ≈ 3 格，跑跳横距 ≈ 6 格，冲刺跳 ≈ 9 格，弹跳板高度 ≈ 7 格
 */

